import { compactCardSlots } from "@goraebap/design-system/recipes/card";
import * as React from "react";
import { mergeClassName } from "../lib/utils";

const styles = compactCardSlots();

function Card({
  className,
  size = "default",
  ...props
}: React.ComponentProps<"div"> & { size?: "default" | "sm" }) {
  return (
    <div
      data-slot="card"
      data-size={size}
      className={mergeClassName(styles.card(), className)}
      {...props}
    />
  );
}

